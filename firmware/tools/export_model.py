"""Turn a trained DS-CNN checkpoint into a C header for the ESP32 detector firmware.

    python firmware/tools/export_model.py L     # -> firmware/detector/model.h

Batch norm is folded into the convolutions; the per-band feature mean/std and the per-class
thresholds (1 false alarm per hour on the tuning set) go into the header too.
Also: `python firmware/tools/export_model.py L --ref clip.wav` prints the PyTorch scores of a
clip (2 s windows every 0.5 s), to compare with the C code (tools/check_core.sh).
"""
import argparse
import json
import sys
from pathlib import Path

import numpy as np
import torch

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from safesound.classes import CLASSES  # noqa: E402
from safesound.frontend import SR, mel_power  # noqa: E402
from safesound.models import DSCNN  # noqa: E402
from safesound.quant import fold_bn  # noqa: E402

ASSETS = ROOT / "firmware" / "assets" / "models"


def load(size):
    d = torch.load(ASSETS / f"p4_{size}_logmel_kd.pt", map_location="cpu", weights_only=False)
    m = DSCNN(d["cfg"]["width"], d["cfg"]["blocks"])
    m.load_state_dict(d["state"])
    return fold_bn(m.eval())


def thresholds(size, budget="@1.0"):
    r = json.load(open(ASSETS / f"p4_{size}_logmel_kd.json"))
    return [r["classes"][c][budget]["threshold"] for c in CLASSES]


def arr(name, a):
    a = np.asarray(a.detach() if hasattr(a, "detach") else a, np.float32).ravel()
    body = ",".join(f"{v:.8g}f" for v in a)
    return f"static const float {name}[{len(a)}] = {{{body}}};\n"


def write_header(size, out):
    m = load(size)
    W, B = m.cfg["width"], m.cfg["blocks"]
    s = [f"// generated by firmware/tools/export_model.py from p4_{size}_logmel_kd.pt - do not edit\n",
         "#pragma once\n", f"#define SS_WIDTH {W}\n#define SS_BLOCKS {B}\n#define SS_CLASSES {len(CLASSES)}\n",
         'static const char *SS_NAMES[] = {' + ",".join(f'"{c}"' for c in CLASSES) + "};\n",
         arr("SS_THRESH", thresholds(size)),
         arr("SS_MEAN", m.feat_mean), arr("SS_INVSTD", 1.0 / m.feat_std)]
    body = list(m.body)
    s += [arr("SS_C0_W", body[0].conv.weight), arr("SS_C0_B", body[0].conv.bias)]
    for b in range(B):
        dw, pw = body[1 + 2 * b].conv, body[2 + 2 * b].conv
        s += [arr(f"SS_DW{b}_W", dw.weight), arr(f"SS_DW{b}_B", dw.bias),
              arr(f"SS_PW{b}_W", pw.weight), arr(f"SS_PW{b}_B", pw.bias)]
    s.append("static const float *SS_DW_W[] = {" + ",".join(f"SS_DW{b}_W" for b in range(B)) + "};\n")
    s.append("static const float *SS_DW_B[] = {" + ",".join(f"SS_DW{b}_B" for b in range(B)) + "};\n")
    s.append("static const float *SS_PW_W[] = {" + ",".join(f"SS_PW{b}_W" for b in range(B)) + "};\n")
    s.append("static const float *SS_PW_B[] = {" + ",".join(f"SS_PW{b}_B" for b in range(B)) + "};\n")
    s += [arr("SS_FC_W", m.fc.weight), arr("SS_FC_B", m.fc.bias)]
    out.write_text("".join(s))
    n = sum(p.numel() for p in m.parameters())
    print(f"wrote {out}: width {W}, blocks {B}, {n} parameters, thresholds "
          + ", ".join(f"{c} {t:.3f}" for c, t in zip(CLASSES, thresholds(size))))


def reference(size, wav):
    """PyTorch scores of a 16 kHz mono WAV: 2 s of silence before it, windows every 0.5 s
    (same as training/evaluation, without the dither)."""
    import wave
    w = wave.open(str(wav))
    assert w.getframerate() == SR and w.getnchannels() == 1
    x = np.frombuffer(w.readframes(w.getnframes()), "<i2").astype(np.float32) / 32768
    pad = 2 * SR
    E = mel_power(np.concatenate([np.zeros(pad, np.float32), x]))
    F = np.log(E + 1.0)
    n = len(x) // (SR // 2)
    ends = [(pad + (k + 1) * (SR // 2) - 512) // 320 for k in range(n)]
    win = torch.from_numpy(np.stack([F[:, e - 99:e + 1] for e in ends]))
    with torch.no_grad():
        p = torch.sigmoid(load(size)(win)).numpy()
    for k, row in enumerate(p):
        print(f"{(k + 1) * 0.5:6.1f} " + " ".join(f"{v:.4f}" for v in row))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("size", choices=["S", "M", "L", "XL"])
    ap.add_argument("--ref", type=Path)
    a = ap.parse_args()
    if a.ref:
        reference(a.size, a.ref)
    else:
        write_header(a.size, ROOT / "firmware" / "detector" / "model.h")
